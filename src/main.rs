//! Conservative nightly policy reconciler for AttoLang backends.
//! Never edits compiler implementations or asserts compiled-guest parity.
use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const BOT_BRANCH: &str = "bot/atto-parity-contracts-v1";
const PR_MARKER: &str = "<!-- atto-parity-controller v1 -->";

#[derive(Clone, Debug)]
struct Target { key: String, repo: String, kind: String }
#[derive(Clone, Debug)]
struct Rule {
    contract: String, phase: String, target: String,
    obligation: String, reason: String,
}
fn rows(path: &str, columns: usize) -> Result<Vec<Vec<String>>, String> {
    let source = fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))?;
    let mut result = Vec::new();
    for (idx, line) in source.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') { continue; }
        let cells: Vec<String> = line.split('|').map(|x| x.trim().to_string()).collect();
        if cells.len() != columns || cells.iter().any(|x| x.is_empty()) {
            return Err(format!("{path}:{}: expected {columns} nonempty pipe-separated fields", idx + 1));
        }
        result.push(cells);
    }
    Ok(result)
}
fn load() -> Result<(Vec<Target>, Vec<Rule>), String> {
    let target_rows = rows("policy/targets.psv", 3)?;
    let contract_rows = rows("policy/contracts.psv", 5)?;
    let mut targets = Vec::new();
    let mut known = BTreeSet::new();
    let mut repos = BTreeSet::new();
    for r in target_rows {
        if !known.insert(r[0].clone()) || !repos.insert(r[1].clone()) {
            return Err(format!("duplicate backend or repository: {}", r[0]));
        }
        if !r[0].chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            || !r[1].starts_with("atto-lang/atto-source.")
            || !r[1].chars().all(|c| c.is_ascii_alphanumeric() || ".-_/".contains(c)) {
            return Err(format!("unapproved target/repository: {} {}", r[0], r[1]));
        }
        targets.push(Target { key: r[0].clone(), repo: r[1].clone(), kind: r[2].clone() });
    }
    if targets.is_empty() { return Err("targets policy is empty".into()); }
    let mut rules = Vec::new();
    let mut pairs = BTreeSet::new();
    for r in contract_rows {
        let (contract, phase, target, obligation, reason) =
            (r[0].clone(), r[1].clone(), r[2].clone(), r[3].clone(), r[4].clone());
        if !known.contains(&target) { return Err(format!("unknown backend {target} in {contract}")); }
        if !matches!(phase.as_str(), "normative" | "accepted" | "proposal") {
            return Err(format!("bad phase {phase} for {contract}"));
        }
        if !matches!(obligation.as_str(), "required" | "optional" | "forbidden" | "deferred") {
            return Err(format!("bad obligation {obligation} for {contract}"));
        }
        if phase == "proposal" && obligation == "required" {
            return Err(format!("proposal cannot impose active parity requirement: {contract}"));
        }
        if !contract.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '.' || c == '_')
            || reason.contains('\t') || reason.contains('\n') {
            return Err(format!("bad contract or reason for {contract}"));
        }
        if !pairs.insert((contract.clone(), target.clone())) {
            return Err(format!("duplicate contract/backend: {contract}/{target}"));
        }
        rules.push(Rule { contract, phase, target, obligation, reason });
    }
    if rules.is_empty() { return Err("contract policy is empty".into()); }
    targets.sort_by(|a, b| a.key.cmp(&b.key));
    rules.sort_by(|a, b| (&a.target, &a.contract).cmp(&(&b.target, &b.contract)));
    Ok((targets, rules))
}
fn selected<'a>(rules: &'a [Rule], key: &str) -> Vec<&'a Rule> {
    rules.iter().filter(|r| r.target == key).collect()
}
fn requirements(rs: &[&Rule]) -> String {
    let mut out = String::from("# Generated by atto-lang/atto-automated-jobs; not compiler certification.\n# proposal phase is non-normative; forbidden means required rejection on that target.\ncontract|phase|obligation|reason\n");
    for r in rs {
        out.push_str(&format!("{}|{}|{}|{}\n", r.contract, r.phase, r.obligation, r.reason));
    }
    out
}
fn report(t: &Target, rs: &[&Rule]) -> String {
    let mut out = format!("# Atto parity obligations: {}\n\nRepository: {}\n\n", t.key, t.repo);
    out.push_str("This policy snapshot is **not** compiled-guest parity evidence. A backend without a trustworthy exact-SHA guest receipt remains **NOT_EXECUTED**, not PASS. Proposals are not ratified requirements.\n\n");
    out.push_str("| Contract | Phase | Obligation |\n| --- | --- | --- |\n");
    for r in rs {
        out.push_str(&format!("| {} | {} | {} |\n", r.contract, r.phase, r.obligation));
    }
    out
}
fn run(cmd: &mut Command) -> Result<String, String> {
    let shown = format!("{cmd:?}");
    let output = cmd.output().map_err(|e| format!("{shown}: {e}"))?;
    if !output.status.success() {
        return Err(format!("{shown}: exit {}: {}", output.status,
            String::from_utf8_lossy(&output.stderr).trim()));
    }
    String::from_utf8(output.stdout).map_err(|e| e.to_string())
}
fn git(dir: &Path, args: &[&str]) -> Result<String, String> {
    run(Command::new("git").arg("-C").arg(dir).args(args))
}
fn gh(args: &[&str]) -> Result<String, String> {
    run(Command::new("gh").args(args))
}
fn pr_state(repo: &str) -> Result<Option<(String, bool)>, String> {
    let out = gh(&[
        "pr", "list", "--repo", repo, "--head", BOT_BRANCH, "--state", "open",
        "--json", "number,isDraft,body",
        "--jq", r#".[] | [.number, .isDraft, (.body | contains("<!-- atto-parity-controller v1 -->"))] | @tsv"#,
    ])?;
    let line = match out.lines().next() { Some(x) => x, None => return Ok(None) };
    let cols: Vec<&str> = line.split('\t').collect();
    if cols.len() != 3 || cols[2] != "true" {
        return Err(format!("refusing to modify unowned PR in {repo}"));
    }
    Ok(Some((cols[0].to_string(), cols[1] == "true")))
}
fn reconcile_one(t: &Target, rs: &[&Rule], workspace: &Path) -> Result<bool, String> {
    if rs.is_empty() { return Ok(false); }
    let existing = pr_state(&t.repo)?;
    if existing.as_ref().is_some_and(|(_, is_draft)| !*is_draft) {
        println!("SKIP {}: existing controller PR is ready for review", t.repo);
        return Ok(false);
    }
    let dir = workspace.join(&t.key);
    if dir.exists() { return Err(format!("workspace collision: {}", dir.display())); }
    let url = format!("https://github.com/{}.git", t.repo);
    run(Command::new("git").args(["clone", "--no-tags", &url]).arg(&dir))?;
    let base = gh(&["repo", "view", &t.repo, "--json", "defaultBranchRef", "--jq", ".defaultBranchRef.name"])?;
    let base = base.trim();
    if base.is_empty() || !base.chars().all(|c| c.is_ascii_alphanumeric() || "/_.-".contains(c)) {
        return Err(format!("invalid default branch for {}", t.repo));
    }
    git(&dir, &["fetch", "origin", base])?;
    git(&dir, &["config", "user.name", "atto-parity[bot]"])?;
    git(&dir, &["config", "user.email", "atto-parity[bot]@users.noreply.github.com"])?;
    let remote = git(&dir, &["ls-remote", "--heads", "origin", BOT_BRANCH])?;
    if !remote.trim().is_empty() && existing.is_none() {
        return Err(format!("bot branch exists without a controller-owned open PR in {}; manual cleanup required", t.repo));
    }
    if remote.trim().is_empty() {
        git(&dir, &["switch", "-c", BOT_BRANCH, &format!("origin/{base}")])?;
    } else {
        git(&dir, &["fetch", "origin", BOT_BRANCH])?;
        git(&dir, &["switch", "-c", BOT_BRANCH, "FETCH_HEAD"])?;
        if let Err(e) = git(&dir, &["merge", "--no-edit", &format!("origin/{base}")]) {
            let _ = git(&dir, &["merge", "--abort"]);
            return Err(format!("manual merge needed for {}: {e}", t.repo));
        }
    }
    let destination = dir.join(".atto/parity/requirements.psv");
    if let Some(parent) = destination.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    fs::write(&destination, requirements(rs)).map_err(|e| e.to_string())?;
    let changed = git(&dir, &["status", "--porcelain", "--", ".atto/parity/requirements.psv"])?;
    if changed.trim().is_empty() {
        println!("NO CHANGE {}", t.repo);
        return Ok(false);
    }
    git(&dir, &["add", "--", ".atto/parity/requirements.psv"])?;
    git(&dir, &["commit", "-m", "chore(parity): reconcile backend obligations"])?;
    git(&dir, &["push", "-u", "origin", BOT_BRANCH])?;
    let body_path = workspace.join(format!("{}.pr.md", t.key));
    let body = format!(
        "{PR_MARKER}\n## AttoLang nightly parity policy reconciliation\n\n\
         This draft proposes a machine-readable obligation snapshot for {}.\n\
         It does NOT implement missing backend behavior or prove guest conformance.\n\
         Required contract gaps need independent compiled-guest testing; forbidden \
         capabilities must reject unsupported input. Proposals are non-normative.\n\n\
         Review the language spec, target profile, and differential guest tests before merge.\n\
         No automatic merge.\n\n{}",
        t.repo, report(t, rs)
    );
    fs::write(&body_path, body).map_err(|e| e.to_string())?;
    let body_file = body_path.to_str().ok_or("non-UTF8 body path")?;
    if let Some((number, true)) = existing {
        gh(&["pr", "edit", &number, "--repo", &t.repo, "--body-file", body_file])?;
        println!("UPDATED draft PR {}#{}", t.repo, number);
    } else {
        gh(&[
            "pr", "create", "--repo", &t.repo, "--draft", "--base", base,
            "--head", BOT_BRANCH, "--title", "chore(parity): reconcile AttoLang contracts",
            "--body-file", body_file,
        ])?;
        println!("CREATED draft PR {}", t.repo);
    }
    Ok(true)
}
fn main_impl() -> Result<(), String> {
    let cmd = env::args().nth(1).unwrap_or_else(|| "plan".to_string());
    let (targets, rules) = load()?;
    if cmd == "validate" {
        println!("VALID: {} targets, {} policy rules", targets.len(), rules.len());
        return Ok(());
    }
    if cmd == "plan" {
        for t in &targets {
            let rs = selected(&rules, &t.key);
            println!("{} {} [{}] rules={}", t.key, t.repo, t.kind, rs.len());
        }
        return Ok(());
    }
    if cmd != "reconcile" { return Err("usage: atto-parity [validate|plan|reconcile]".into()); }
    if env::var("GH_TOKEN").unwrap_or_default().is_empty() {
        return Err("reconcile requires a scoped GitHub App GH_TOKEN".into());
    }
    let workspace = PathBuf::from(env::var("ATTO_PARITY_WORKSPACE")
        .unwrap_or_else(|_| "target/atto-parity-workspace".to_string()));
    fs::create_dir_all(&workspace).map_err(|e| e.to_string())?;
    let reports = PathBuf::from("target/parity-reports");
    fs::create_dir_all(&reports).map_err(|e| e.to_string())?;
    let max = env::var("ATTO_PARITY_MAX_PRS").ok()
        .and_then(|x| x.parse::<usize>().ok()).unwrap_or(5).min(10);
    let mut updated = 0;
    let mut errors = Vec::new();
    for t in &targets {
        let rs = selected(&rules, &t.key);
        fs::write(reports.join(format!("{}.md", t.key)), report(t, &rs))
            .map_err(|e| e.to_string())?;
        if updated >= max { println!("BUDGET SKIP {}", t.repo); continue; }
        match reconcile_one(t, &rs, &workspace) {
            Ok(true) => updated += 1,
            Ok(false) => {},
            Err(e) => { eprintln!("BLOCKED {e}"); errors.push(e); }
        }
    }
    println!("parity reconciliation: {updated} draft PRs created/updated; {} blocked", errors.len());
    if !errors.is_empty() { return Err(format!("{} target(s) blocked", errors.len())); }
    Ok(())
}
fn main() {
    if let Err(e) = main_impl() {
        eprintln!("ERROR: {e}");
        std::process::exit(1);
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn checked_policy_loads() {
        let (targets, rules) = load().expect("checked-in policy should parse");
        assert!(targets.len() >= 5);
        assert!(rules.len() >= 5);
    }
    #[test]
    fn rendering_is_stable_and_marks_uncertainty() {
        let r = Rule {
            contract: "trap.result.v1".into(), phase: "normative".into(),
            target: "rs".into(), obligation: "required".into(), reason: "guest proof".into(),
        };
        let s = requirements(&[&r]);
        assert!(s.contains("trap.result.v1|normative|required|guest proof"));
        assert!(s.contains("not compiler certification"));
        let t = Target { key: "rs".into(), repo: "atto-lang/atto-source.rs".into(), kind: "compiler".into() };
        assert!(report(&t, &[&r]).contains("NOT_EXECUTED"));
    }
    #[test]
    fn no_unscoped_repositories() {
        let (targets, _) = load().unwrap();
        assert!(targets.iter().all(|t| t.repo.starts_with("atto-lang/atto-source.")));
    }
}
